"""경력 거르기의 **말 규칙**만 모은다 — 누구를 후보로 볼지 가리는 자.

`career.py` 는 파일을 읽고 모델에 묻고 보고하는 절차라 거의 안 바뀌지만, 여기 규칙은
실제 공고를 보다가 "이건 오탐이다" 를 만날 때마다 손댄다. 바뀌는 이유가 다르다
(`filter.py` / `filter_words.py` 와 같은 이유로 나눈다).

    accepts_newbie(경력칸)   사이트가 "신입도 된다" 고 말했나
    demands_years(지원자격)   재직 연수를 요구하는 줄. 없으면 None

## 이 규칙은 **후보를 좁히는 데까지만** 쓴다

여기서 걸린 것이 곧 "모순된 공고" 가 아니다. 판정은 모델이 한다 (`career.py`).
낱말만으로는 가릴 수 없는 것이 실제로 있었다 — `경력직 지원자의 경우, 필요 시
레퍼런스 체크 진행 예정` 은 `경력직` 이 들어 있지만 **경력직도 받는다**는 말이지
요구가 아니다.
"""
from __future__ import annotations

import re

# **"경험" 과 "경력 연수" 는 다른 것이다.** (2026-09-13 사용자)
#
#   "개발 경험이 있으신 분" · "Spring 에 능숙한 분"   → 갖춰야 할 **역량**이다.
#                                                     신입도 프로젝트·학습으로 가진다
#   "경력 3년 이상" · "5~10년 정도"                   → **재직 연수**다. 이것만이 모순
#
# 처음에 "경험"·"능숙" 까지 잡았더니 신입 가능 66행 중 42행(64%)이 걸렸다. 연수를
# 요구하는 말만 보면 14행이 된다.
YEARS = re.compile(
    r"(경력|경험|근무|실무)[^\n]{0,12}?(\d{1,2})\s*(년|개월)\s*(이상|이후|차|정도|내외|~)"
    r"|(\d{1,2})\s*(년|개월)\s*(이상|차)[^\n]{0,10}?(경력|경험|근무|실무)"
    r"|경력\s*직"
    r"|(\d{1,2})\s*[~-]\s*(\d{1,2})\s*년")

# 같은 줄에 이것이 있으면 **신입도 받는다는 뜻**이다 — 모순이 아니다.
# 실측: `신입 / 경력 1년 이상 ~ 3년 이하` · `신입 또는 백엔드 개발 경력 5년 내외이신 분`.
# 이 규칙 하나로 후보 14행이 9행이 된다.
SAME_LINE_OK = re.compile(r"신입|무관|우대|졸업\s*예정")

# 사이트가 경력 칸에 적는 말. 이 중 하나면 "신입도 된다" 는 뜻이다.
# 실측 66행: `신입 · 경력` `신입·경력` `경력무관` `신입` `신입~5년` — 띄어쓰기가 흔들린다.
_NEWBIE_FIELD = re.compile(r"^(신입|경력무관)")


def accepts_newbie(value: str | None) -> bool:
    """사이트가 **신입도 지원할 수 있다**고 적었나."""
    return bool(_NEWBIE_FIELD.match((value or "").replace(" ", "")))


def demands_years(qualification: str | None) -> str | None:
    """재직 연수를 요구하는 **줄**. 없으면 `None`.

    **우대사항은 보지 않는다.** 우대는 없어도 지원할 수 있으므로 "신입 가능" 과
    모순되지 않는다 — 실측으로 `교보다솜케어` 가 그랬다. 자격은 `경력 무관` 인데
    우대에만 `경력 1년 이상` 이 있었다.

    줄을 통째로 돌려주는 이유는 **모델에게 그 줄을 보여 주기 위해서**다. 그리고
    사람이 보고 CSV 에서 왜 걸렸는지 되짚을 수 있어야 한다.
    """
    for line in (qualification or "").split("\n"):
        if YEARS.search(line) and not SAME_LINE_OK.search(line):
            return line.strip()
    return None


def candidate(row: dict) -> str | None:
    """이 공고가 **모델에게 물어볼 후보**인가. 맞으면 걸린 줄을 돌려준다.

    실측(2026-09-13, `merged_core.csv` 66행): 신입 가능 66행 → 후보 **9행(13%)**.
    """
    if not accepts_newbie(row.get("경력")):
        return None
    return demands_years(row.get("지원자격"))


# ── 대놓고 경력직인 공고 빼기 ────────────────────────────────────────────
#
# **위의 `candidate` 와 반대 방향이다.** 저기는 "신입이라 적어 놓고 경력을 요구하는"
# 모순을 찾고, 여기는 "경력 칸이 아예 경력직이라고 말하는" 것을 본다.
#
# ## 왜 이것이 필요해졌나 — `role.py` 가 경력 칸을 고치기 시작했다
#
# 수집 단계는 사이트 검색에서 신입으로 좁힌다(`.env` 의 YOE). 그래서 예전에는 경력
# 칸에 `신입`·`경력무관` 밖에 안 들어왔고, `accepts_newbie` 로 후보를 좁히는 것이
# 맞는 게이트였다. 실측으로 `history/history_read.csv` 949행(사이트가 준 경력 값)에
# 이 규칙을 대면 **한 건도 안 걸린다** — 이 규칙은 사이트 값에는 작동하지 않는다.
#
# 그런데 `role.py` 가 부문별 실제 값으로 그 칸을 덮어쓰면서(`role.py` 의 `OVERWRITE`)
# 신입불가 값이 처음 생겼다. 실측(2026-09-22):
#
#     csv/merged.csv        676행 중 신입불가   0행   ← 사이트가 준 값
#     csv/merged_role.csv   588행 중 신입불가  36행   ← role.py 가 고친 값
#
# 위캔소프트(`GI_Read/49811179`)가 그 예다. 사이트는 `신입·경력` 이라 적었는데 그림
# 본문 첫 줄이 `위캔소프트 경력자 모집 / 3년이상 웹개발자 모집합니다` 였다. role.py 가
# `경력 3년이상` 으로 바로잡았고, **정확해진 그 값이 `accepts_newbie` 를 못 통과해
# 오히려 거르기를 빠져나갔다.**
#
# ## 부문 단위로 본다 — 한 부문이라도 열려 있으면 남긴다
#
# 통합 공고는 한 칸에 부문 여럿을 적는다. 그중 하나라도 신입을 받으면 지원할 수 있다.
#
#     [Web 개발] 유관 경력 2년 이상 / [SW 개발(Server)] 신입 또는 경력 3년 이상
#                                     ^^^^ 이 부문으로 지원한다 → 남긴다
#
#     정보전략팀-백엔드: 6년 이상 / 플랫폼개발팀-백엔드: 3년 이상 /
#     플랫폼개선팀-Java백엔드: 5년 이상 / 플랫폼개선팀-ReactJS프론트엔드: 8년 이상
#                                     → 열린 부문이 하나도 없다 → 뺀다
#
# **`/` 는 앞뒤에 공백이 있을 때만 부문 구분이다.** 그냥 가르면 `React/Spring Boot
# 개발자` 가 두 부문이 된다.
_SEGMENT = re.compile(r"\s/\s|\s·\s|,\s")

# 이 말이 있으면 그 부문은 **열려 있다.** `SAME_LINE_OK` 와 같은 뜻이되, 경력 칸에만
# 나오는 표기(`미기재`·`명시 없음`)를 더한다.
#
# **`우대` 를 열린 것으로 친다.** `8~9년차 우대` 는 연수를 *요구*하는 것이 아니라
# 선호한다는 말일 수 있다. 가를 신호가 없으므로 남긴다 — 지우는 판단에 "모르겠으면
# 지운다" 는 없다 (2026-09-13 사용자). 실측에서 이 갈래로 남는 것은 1행이다.
_OPEN = re.compile(r"신입|무관|미기재|명시\s*없|졸업\s*예정|우대")

# 재직 연수를 요구하는 말. `YEARS` 와 달리 **`경력직` 을 안 본다** — 경력 칸의
# `신입·경력` 은 "경력도 받는다" 는 뜻이라 여기서 보면 전부 걸린다.
_YEARS = re.compile(
    r"(\d{1,2})\s*년\s*(이상|차|이후|부터)"
    r"|(\d{1,2})\s*년\s*[~\-–]\s*(\d{1,2})\s*년"
    r"|(\d{1,2})\s*[~\-–]\s*(\d{1,2})\s*년"
    r"|경력\s*[(\s]*(\d{1,2})")


def closed_to_newbie(value: str | None) -> str | None:
    """경력 칸이 **신입을 배제하는가.** 맞으면 그렇게 말한 부문, 아니면 `None`.

    부문을 돌려주는 이유는 `demands_years` 와 같다 — 보고 CSV 에서 사람이 왜 빠졌는지
    되짚을 수 있어야 한다.

    빈 칸은 `None` 이다. **안 적힌 것을 경력직으로 읽으면 안 된다** — 실측으로
    `csv/merged_role.csv` 588행 중 20행이 빈 칸이고, 그건 수집이 못 가져온 것이지
    회사가 경력직이라고 말한 것이 아니다.
    """
    text = (value or "").strip()
    if not text:
        return None
    closed = []
    for part in _SEGMENT.split(text):
        part = part.strip()
        if not part:
            continue
        if _OPEN.search(part):
            return None              # 한 부문이라도 열려 있으면 지원할 수 있다
        if _YEARS.search(part):
            closed.append(part)
    return closed[0] if closed else None
