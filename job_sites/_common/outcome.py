"""수집이 **온전했는가**를 판정한다. 종료 코드는 오케스트레이터와 맺은 계약이라
사이트마다 따로 두면 한 곳이 어긋나도 알아채기 어렵다 (`runlock.ALREADY_RUNNING` 과 같다).

## 왜 필요했나

목록은 멀쩡히 받았는데 **상세를 한 건도 못 받은** 실행이 있었다 (Pathsdog 의 상세
도구가 죽어 29건 전부 `internal_error`). 공고 하나가 실패하는 것은 견뎌야 하므로
세고 넘어가게 해 뒀는데, **전부 실패해도 똑같이 넘어가 종료 코드 0** 을 냈다.
화면에는 `정상 · 0행` 이라고 찍혔다 — 사이트에 공고가 29건 있는데도.

## 판정

    걷어서 저장한 행이 없는데, 상세 실패가 하나라도 있었다  →  INCOMPLETE

`0행` 자체는 정상일 수 있다. 조건에 맞는 공고가 없거나, 받아 놓고 근무지·고용형태로
다 걸러졌을 수 있다. **그 둘과 "못 받은 것" 을 가르는 것이 이 판정이다** — 남은 것이
없는데 잃은 것이 있으면, 이 실행만 보고는 *사이트에 공고가 없는 건지 우리가 못 받은
건지* 알 수 없다. 알 수 없는 것을 `정상` 이라고 말하면 안 된다.

비율(절반 넘게 실패 등)로 자르지 않는다. 어디서 자를지 근거가 없고, 그 선을 어디에
두든 임의값이 하나 더 늘 뿐이다. **하나라도 건졌으면** 그 실행은 무언가를 해냈고,
잃은 건수는 요약에 찍혀 사람이 본다.
"""
from __future__ import annotations

# 온전히 못 걷었다. **모은 것이 있으면 저장은 하되** 성공으로 세지 않는다.
# 차단(`stats["차단"]`)이 내는 코드와 같다 — 둘 다 "여기까지밖에 못 걷었다" 이다.
INCOMPLETE = 2


def incomplete(stats: dict, rows) -> bool:
    """걷은 것이 없는데 **잃은 것이 있는가.**

    `rows` 는 저장한 행들(또는 그 개수). `stats["상세실패"]` 는 상세를 물어봤다가
    실패한 건수다.

    공고번호가 없어 **아예 안 물어본** 것(`번호없음`)은 세지 않는다 — 그건 상세를
    주는 쪽의 잘못이 아니라 목록이 그렇게 생긴 것이고, 실패로 읽으면 멀쩡한 실행이
    실패가 된다.
    """
    saved = rows if isinstance(rows, int) else len(rows or ())
    return saved == 0 and stats.get("상세실패", 0) > 0
