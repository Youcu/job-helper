"""**한 공고에 여러 직군이 섞여 있는가** 를 글자만 보고 가른다. 그물도 모델도 안 탄다.

    role_words.looks_mixed(row, body)  →  걸린 낱말들 (없으면 빈 목록)

여기서 하는 일은 **후보 고르기**뿐이다. 어느 부문이 내 직군인지, 그 부문이 무엇을
요구하는지는 글자로 못 가른다 — 회사마다 공고를 다르게 쓴다. 그건 `src/role.py` 가
모델에게 묻는다.

## 왜 기계가 먼저 거르나

모델은 느리고 돈이 든다. 실측(2026-09-18, 672행)으로 제목 신호에 걸리는 것은
**8%** 뿐이다. 나머지 92%는 물어볼 것도 없이 단일 직군이다.

## 제목이 본문보다 실하다

처음에는 본문의 `모집부문` 횟수를 세려 했다. **안 된다** — 사람인 28건을 실제로
받아 세어 보니 통합 공고인 한양이엔지도 1회였고, 단일 공고도 1회였다. 표의 열
이름이라 거의 모든 공고에 한 번 나온다.

제목은 다르다. 회사가 통합 공고를 낼 때 **제목에 그렇게 적는다** —
`각 부문별 직원모집` · `2026년 3분기 분야별 공개채용` · `하반기 각 부문 수시채용`.
`merged_rated.csv` 166행에서 18건이 걸렸고 **전부 진짜 통합 공고**였다.

## 그래도 본문을 함께 본다

제목만 보면 `[안랩] 2026 연구소 집중 채용` 처럼 **부문 낱말이 없는** 통합 공고를
놓친다. 본문에 `모집부문` 이 **여러 번** 나오면 그것도 후보로 올린다 — 한 번은
표 머리말이지만 여러 번은 부문이 여럿이라는 뜻이다.

## 넓게 걸어도 된다

헛걸린 공고의 대가는 **모델에게 한 번 더 묻는 것**뿐이고, 모델은 "직군 하나뿐이다"
라고 답한다. 놓친 공고의 대가는 다른 직군의 기술과 자격요건이 최종본까지 가는
것이다. 둘은 값이 다르므로 **넓게** 건다.
"""
from __future__ import annotations

import re

# 제목에 이것이 있으면 후보다. 회사가 "여러 자리를 한 공고에 담았다" 고 밝히는 말이다.
TITLE_SIGNALS = (
    r"각\s*부문", r"부문\s*별", r"분야\s*별", r"직군\s*별", r"각\s*분야",
    r"모집\s*분야", r"공개\s*채용", r"집중\s*채용", r"수시\s*채용",
    r"통합\s*채용", r"채용\s*통합", r"전\s*부문", r"부문\s*채용",
)
TITLE = re.compile("|".join(TITLE_SIGNALS))

# 본문 신호는 **흔한 말과 드문 말을 갈라서** 센다.
#
# 실측(2026-09-18, 본문 682건)으로 낱말마다 흔한 정도가 크게 다르다.
#
#     모집분야  267건(39%)   모집부문  145건(21%)   ← 표 머리말이라 아무 데나 있다
#     채용분야   12건         채용부문    8건
#     모집직무    7건         부문 안내   2건        ← 이 말을 쓰면 대개 진짜 통합 공고다
#
# 흔한 말에 1회 기준을 걸면 절반이 후보가 되어 모델 값이 못 쓰게 오른다. 드문 말에
# 2회 기준을 걸면 **아무것도 안 걸린다** — 위 표의 오른쪽은 2회 이상이 0건이다.
# 실제로 `[안랩] 2026년 연구소 상시채용`(기술 45개짜리 통합 공고)이 `채용부문` 을
# 한 번 쓰고 그대로 빠져나갔다.
COMMON_SIGNAL = re.compile(r"모집\s*부문|모집\s*분야")
COMMON_MINIMUM = 2

RARE_SIGNAL = re.compile(r"채용\s*부문|채용\s*분야|모집\s*직무|부문\s*안내|직군\s*안내")
RARE_MINIMUM = 1

TITLE_COLUMN = "공고명"


def title_hits(title: str) -> list[str]:
    """제목에서 걸린 낱말들. 같은 말이 여러 번이면 한 번만 센다."""
    found: list[str] = []
    for one in TITLE.findall(title or ""):
        word = " ".join(one.split())
        if word and word not in found:
            found.append(word)
    return found


def body_hits(body: str) -> list[str]:
    """본문에서 걸린 근거들. 빈 목록이면 안 걸렸다.

    **흔한 말과 드문 말의 기준이 다르다** — 위 두 상수의 설명을 보라.
    """
    body = body or ""
    found: list[str] = []
    common = len(COMMON_SIGNAL.findall(body))
    if common >= COMMON_MINIMUM:
        found.append("본문에 부문 낱말 %d회" % common)
    rare = RARE_SIGNAL.findall(body)
    if len(rare) >= RARE_MINIMUM:
        found.append("본문에 %s" % " ".join(dict.fromkeys(
            " ".join(one.split()) for one in rare)))
    return found


def looks_mixed(row: dict, body: str = "") -> list[str]:
    """이 공고가 여러 직군을 담았을 후보인가. **걸린 근거**를 돌려준다.

    빈 목록이면 후보가 아니다. 근거를 돌려주는 이유는 리포트에 적기 위해서다 —
    왜 물어봤는지 못 되짚으면 규칙을 고칠 수가 없다.
    """
    return (["제목: %s" % word for word in title_hits(row.get(TITLE_COLUMN, ""))]
            + body_hits(body))


# ── 절을 못 갈랐는가 ─────────────────────────────────────────────────────
#
# **두 번째 후보 고르기다.** 위의 `looks_mixed` 와 묻는 것이 다르다.
#
#     looks_mixed     "여러 직군이 섞였나"      → 어느 부문이 내 것인지 묻는다
#     needs_sections  "절 가르기가 실패했나"    → 이 글에서 자격요건을 뽑아 달라 한다
#
# ## 왜 필요한가 — 회사가 `자격요건` 이라고 안 쓴다
#
# 절 가르기(`_common/sections.py`)는 머리말을 찾아 본문을 가른다. 그런데 회사가
# 그 말을 안 쓰면 아무것도 못 가른다. 실측(2026-09-22, `merged_role` 599행 중
# 지원자격이 빈 23행):
#
#     머리말이 아예 없다        9행   `4. 필요사항: 설계 및 개발이 모두 가능하면…`
#     머리말은 있는데 못 갈랐다   6행   표 형식 — `근무부서 담당업무 자격요건 우대사항`
#                                    이 한 줄에 열 머리글로 나란히 온다
#     본문 자체가 없다          4행
#     본문이 껍데기다           4행
#
# 앞의 15행은 **글은 있는데 우리가 못 읽은 것**이다. 규칙을 아무리 넓혀도 다음
# 형태에서 또 뚫린다 — 회사마다 공고를 다르게 쓴다. 그래서 **규칙이 못 가르면
# 이상한 경우로 보고 모델이 직접 읽는다** (2026-09-22 사용자).
#
# ## 빈 칸은 조용히 판단을 바꾼다
#
# `지원자격` 이 비면 뒤 단계가 재료 없이 지나간다. 핵심 기술 게이트도 경력 판정도
# 그 칸을 본다. 빈 칸은 "조건이 없다" 가 아니라 **"우리가 못 읽었다"** 인데, 코드는
# 둘을 구별하지 못한다.
#
# ## 본문이 없으면 후보가 아니다
#
# 모델에게 줄 글이 없으면 물어볼 것도 없다. 빈 글을 주면 빈 답을 받고, 그 빈 답이
# "조건이 없다" 로 굳는다. 그건 수집기를 고쳐야 하는 별개 문제다.
QUALIFICATION = "지원자격"

# 이만큼보다 짧으면 본문이 껍데기다 — 전형절차·유의사항만 있고 내용이 없다.
# 실측으로 `(주)슈튜` 의 본문이 176자였고 통째로 채용절차 안내였다.
MIN_BODY = 400


def needs_sections(row: dict, body: str = "", heading: str = "") -> str | None:
    """절 가르기가 실패했는가. 맞으면 그 까닭, 아니면 `None`.

    `heading` 은 인재상 표기 머리말이다(`_common.sections.VALUES_HEADING`). 그 대목은
    자격요건이 아니므로 **빼고 잰다** — 안 그러면 인재상만 든 칸이 "차 있다" 로 보인다.
    """
    text = row.get(QUALIFICATION) or ""
    if heading and heading in text:
        text = text.split(heading, 1)[0]
    if text.strip():
        return None                      # 이미 차 있다
    body = (body or "").strip()
    if not body:
        return None                      # 줄 글이 없다 — 수집기 문제다
    if len(body) < MIN_BODY:
        return None                      # 껍데기다 — 뽑을 것이 없다
    return "지원자격이 빔 · 본문 %d자" % len(body)


# ── 세 번째 게이트: 제목이 **다른 직군**을 말한다 ────────────────────────
#
# **이 단계가 25% 만 검사하고 있었다.** `looks_mixed` 는 "여러 직군을 한 장에 담은"
# 공고를 찾는 자라, **단일 직군 공고는 아예 안 물어봤다.** 실측(2026-09-23):
#
#     직군 단계 입력 656행 중 물어본 것 163행(25%) · 안 물어본 것 493행(75%)
#
# 그래서 `보안솔루션 엔지니어 모집` · `FDE(Forward Deployed Engineer)` ·
# `화상상담솔루션 DevOps 엔지니어` 같은 **명백히 다른 직군의 단일 공고가 통째로
# 통과**했다. 마지막 것은 최종 41행에까지 들어 있었다 (2026-09-23 사용자 지적).
#
# ## 왜 여태 안 드러났나 — 수집기가 가려 주고 있었다
#
# 사이트 검색이 `JOB_ROLES` 로 직무 코드를 걸어 준다. 그게 거칠게 걸러 주니 대부분은
# 맞는 직군이 온다. **거친 그물 하나에 기대고 있었던 것**이고, 그 사이로 새는 것을
# 잡는 자가 없었다.
#
# ## 제목만 본다
#
# 본문까지 보면 `저희는 데이터 엔지니어도 뽑습니다` 같은 곁말에 걸려 후보가 폭증한다.
# 제목은 회사가 그 자리를 뭐라고 부르는지를 말한다. 실측으로 제목만 봐서 42행이
# 늘었고(163 → 205행, 31%), 표본이 전부 진짜였다.
#
# **내 직군 낱말이 제목에 있으면 안 건다.** `Java 백엔드/데이터 파이프라인 개발자`
# 처럼 둘 다 있으면 내 자리일 가능성이 크고, 그건 `looks_mixed` 나 모델이 볼 일이다.
FOREIGN_ROLES = {
    "데이터엔지니어": r"데이터[\s가-힣]{0,4}엔지니어|Data\s*Engineer|\bETL\b|데이터\s*파이프라인",
    "데브옵스": r"DevOps|데브옵스|\bSRE\b|인프라\s*엔지니어|클라우드\s*(시스템\s*)?엔지니어",
    "머신러닝": r"Machine\s*Learning|\bML\s*Engineer|머신\s*러닝|딥\s*러닝|Researcher",
    "보안": r"보안\s*(엔지니어|솔루션|개발|관제|컨설)|정보\s*보안|침해\s*대응|취약점\s*진단",
    "QA": r"(?<![A-Za-z])QA(?![A-Za-z])|테스트\s*엔지니어|품질\s*보증",
    "임베디드": r"임베디드|펌웨어|Firmware|\bMCU\b|\bRTOS\b",
    "앱": r"안드로이드|Android|(?<![A-Za-z])iOS(?![A-Za-z])|앱\s*개발|Flutter|모바일\s*개발",
    "퍼블리셔": r"퍼블리셔|마크업\s*개발",
    "DBA": r"(?<![A-Za-z])DBA(?![A-Za-z])",
    "블록체인": r"블록체인|Blockchain",
    "기술지원": r"Forward\s*Deployed|기술\s*지원\s*엔지니어|솔루션\s*엔지니어|필드\s*엔지니어",
}

# 이 말이 제목에 있으면 내 자리일 수 있다 — 안 건다.
# **`JOB_ROLES` 와 따로 적는다.** 저건 사이트 검색 코드이고 이건 제목의 말이다.
MINE_WORDS = re.compile(
    r"백엔드|Back[\s-]?end|서버\s*개발|서버개발|웹\s*개발|웹개발|웹\s*서비스\s*개발"
    r"|풀스택|Full[\s-]?stack|프론트|Front[\s-]?end|웹\s*프로그래머"
    r"|Java|Spring|Node|Django|FastAPI|\bPHP\b|Nest", re.IGNORECASE)


def title_unclear(row: dict) -> str | None:
    """제목만으로 **내 직군인지 알 수 있는가.** 모르겠으면 그 까닭, 알겠으면 `None`.

    ## 화이트리스트다 — 블랙리스트가 아니다 (2026-09-23 사용자)

    처음에는 `FOREIGN_ROLES` 에 걸릴 때만 물었다. **그건 열린 집합이라 영원히
    미완성이다** — 실측으로 `모션 플래닝 엔지니어` · `자율주행 엔지니어` ·
    `AX매니저` · `SW Engineer` 가 그 표를 통째로 빠져나갔다. 직군 이름은 회사마다
    새로 지어 붙이므로 다 적을 수가 없다.

    **내가 원하는 것은 닫힌 집합이다.** `MINE_WORDS` 에 없으면 묻는다 —
    갈래가 둘뿐이면 `if` 와 `else` 로 끝나지 `if` 를 두 번 쓰지 않는다.

        지금 (화이트리스트)   656행 중 후보 457행 (70%)
        전  (블랙리스트)     656행 중 후보 203행 (31%)

    ## `FOREIGN_ROLES` 는 남는다 — 이제 **까닭을 적는 자**다

    후보로 올리는 일은 안 한다. 다만 `제목에 내 직군 낱말이 없다` 보다
    `제목이 다른 직군: 보안` 이 보고에서 훨씬 쓸모 있다. 사람이 왜 물었는지를
    한눈에 본다.
    """
    title = row.get(TITLE_COLUMN) or ""
    if MINE_WORDS.search(title):
        return None
    foreign = [name for name, pattern in FOREIGN_ROLES.items()
               if re.search(pattern, title, re.IGNORECASE)]
    if foreign:
        return "제목이 다른 직군: %s" % " · ".join(foreign)
    return "제목에 내 직군 낱말이 없다"
